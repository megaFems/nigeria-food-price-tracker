"""Write reports/data_quality.md: the data problems met in this project, with numbers from the data.

Usage:  python pipeline/report_quality.py   (run pipeline/clean_wfp.py and pipeline/indices.py first)
"""
import pathlib

import pandas as pd

from clean_wfp import BASKET, KNOWN_GAP, OUT as CLEAN
from indices import OUT_MARKED
from profile_wfp import latest

ROOT = pathlib.Path(__file__).resolve().parents[1]
REPORT = ROOT / "reports" / "data_quality.md"


def typical(df: pd.DataFrame, state: str, item: str, month: str) -> float:
    return df.loc[(df["state"] == state) & (df["commodity"] == item) & (df["month"] == month), "price_ngn"].median()


def main() -> None:
    raw = pd.read_csv(latest("wfp_food_prices_nga"), low_memory=False)
    raw = raw[raw["date"].astype(str).str.match(r"\d{4}-")].copy()
    for c in ("price", "usdprice"):
        raw[c] = pd.to_numeric(raw[c], errors="coerce")
    raw["month"] = raw["date"].str[:7]
    ended = raw.groupby("admin1")["month"].max()
    stopped = ended[ended <= KNOWN_GAP[1][:7]]
    rate = raw["price"] / raw["usdprice"]
    typical_rate = rate.groupby(raw["month"]).transform("median")
    bad_usd = ((rate > 5 * typical_rate) | (rate < typical_rate / 5)).sum()

    df = pd.read_parquet(CLEAN)
    df["month"] = pd.to_datetime(df["month"]).dt.strftime("%Y-%m")
    b = df[df["in_basket"]]
    gap = [str(m) for m in pd.period_range(KNOWN_GAP[0], KNOWN_GAP[1], freq="M")]
    no_gap_prices = [i for i in BASKET if not b["month"][b["commodity"] == i].isin(gap).any()]
    markets = df[df["month"] >= "2017-07"].groupby("month")["market_id"].nunique()
    outliers, low = int(df["is_outlier"].sum()), int(df["low_coverage"].sum())

    swap = ["Oranges", "Bananas", "Spinach", "Watermelons", "Eggs", "Sugar"]
    rows = [{"food (Yobe)": i, **{m: round(typical(df, "Yobe", i, m)) for m in ("2021-03", "2021-05", "2021-06")}}
            for i in swap]
    april = b[(b["state"] == "Yobe") & (b["month"] == "2021-04")]["commodity"].nunique()
    sugar = [{"month": m, **{s: typical(df, s, "Sugar", m) for s in ("Borno", "Yobe")}}
             for m in ("2024-08", "2024-10", "2024-11", "2025-01", "2026-05", "2026-07", "2026-08", "2026-09", "2026-11")]
    milk = {m: typical(df, "Borno", "Milk (powder)", m) for m in ("2022-03", "2022-04", "2022-05", "2023-02")}
    marked = pd.read_parquet(OUT_MARKED)
    n_sus = int(marked["suspect"].ne("").sum())

    s = [
        "# Working with the data: difficulties and inconsistencies\n",
        "_Generated by `pipeline/report_quality.py`. Source: WFP via HDX (CC BY-IGO)._\n",
        "What made the data hard to work with while building this tracker, and how each point was handled. The files do not say why they happened, so causes are not assumed.\n",
        "## Gaps",
        f"- {len(no_gap_prices)} of the {len(BASKET)} basket foods have no North-East price at all from {gap[0]} to {gap[-1]} "
        f"({len(gap)} months). _Handled: left blank and shaded on charts._",
        f"- {len(stopped)} of {len(ended)} states had stopped by {KNOWN_GAP[1][:7]}. Adamawa stops in "
        f"{ended['Adamawa']}. _Handled: no national claim is made._",
        f"- From July 2017 the number of markets reporting in a month ranges from {markets.min()} to {markets.max()}. "
        "_Handled: the index compares like with like._",
        f"- {low:,} of {len(df):,} North-East prices ({low / len(df):.1%}) come from a food and month with fewer than 10 markets. "
        "_Handled: flagged._\n",
        "## Prices that look wrong",
        f"- {outliers} prices ({outliers / len(df):.1%}) are above 5x or below 1/5 of the typical price that month. "
        "_Handled: flagged, left out of the index._",
        "- Milk powder, Borno, typical price per 400 g: " + ", ".join(f"{m}: {v:,.0f}" for m, v in milk.items())
        + " naira. No reading exists between May 2022 and February 2023. _Handled: not counted._",
        f"- In all, {n_sus:,} of {len(marked):,} basket prices since July 2017 are suspected or not comparable, most of them from before September 2018 or spinach. "
        "_Handled: shown with their effect in the findings report, not counted in any final figure._",
        f"- {bad_usd:,} dollar prices imply an exchange rate more than 5x away from the typical rate that month. "
        "_Handled: the dollar column is never used._\n",
        "## Yobe, May 2021: prices that look assigned to the wrong foods",
        "The May values for oranges, bananas and spinach match the usual price of eggs, spinach and bananas. "
        f"The month before, April 2021, has only {april} of {len(BASKET)} basket foods in Yobe.\n",
        pd.DataFrame(rows).to_markdown(index=False),
        "\n_Handled: all six foods are left out for Yobe that month._\n",
        "## Yobe, June 2018: eleven foods halve at once and stay there",
        "Typical Yobe price, in naira:\n",
        pd.DataFrame([{"food (Yobe)": i, **{m: round(typical(df, "Yobe", i, m)) for m in ("2018-05", "2018-06", "2018-09")}}
                      for i in ("Beans (red)", "Beans (white)", "Cowpeas", "Groundnuts", "Maize flour", "Millet", "Rice (imported)",
                                "Rice (local)", "Salt", "Sorghum", "Sugar", "Oil (palm)", "Oil (vegetable)")]).to_markdown(index=False),
        "\nBorno shows no such step. Both oils follow over the next two months. A change in the measure would explain it, but this is "
        "not confirmed. _Handled: final figures start in September 2018._\n",
        "## Whole surveys that jump and come back",
        "Yobe in October 2020 (basket down 22%, then up 31%) and Borno in April 2022 (down 27%, then up 45%; eggs, meat, fruit and oils "
        "are near half price). _Handled: those state months are not counted._\n",
        "## Sugar: about 5x higher, twice, in every area reporting",
        "Typical price per 500 g, in naira:\n",
        pd.DataFrame(sugar).to_markdown(index=False, floatfmt=",.0f"),
        "\nA larger pack entered as 500 g would explain it, but this is not confirmed. _Handled: not counted. "
        "Counting them would raise the basket by about 7% in those months._\n",
        "## Spinach",
        "The typical price sits near 50 naira for most of 2017 to 2023, while Borno is 5 to 9x higher from April to "
        "November 2019. _Handled: not used in the index._\n",
        "## Checking against a second source",
        "Two National Bureau of Statistics tables (Selected Food Price Watch, November 2024 and January 2025) were checked. "
        "Neither covers sugar, bananas, powdered milk, oranges, salt or spinach. Both give zone averages and the highest and "
        "lowest state rather than every state, and the food list and some pack sizes change between them.\n",
        "## For anyone using this data\n",
        "- Compare each price with the months before and after, not only with other markets: a whole month can be off.",
        "- Check that a price is plausible for its stated pack size.",
        "- Compare the same markets over time, because the reporting markets change.",
        "- Leave gaps blank, and say so on the chart.\n",
        "## Context\n",
        "Much of this data comes from areas affected by conflict, where collecting prices is hard, and this tracker could not "
        "exist without it. The points above have not yet been raised with the publisher.",
    ]
    REPORT.write_text("\n".join(s) + "\n", encoding="utf-8")
    print(f"wrote {REPORT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
