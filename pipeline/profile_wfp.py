"""Profile the latest raw WFP Nigeria food-price file and write reports/profile_wfp.md.

Answers the questions that decide the design: what time span, which states, markets and commodities,
which units and price types, how complete recent months are, duplicates, and suspicious prices.

Usage:  python pipeline/profile_wfp.py
"""
import json
import pathlib

import duckdb
import pandas as pd

ROOT = pathlib.Path(__file__).resolve().parents[1]
RAW = ROOT / "data" / "raw"
OUT = ROOT / "reports" / "profile_wfp.md"
KEY = ["date", "market_id", "commodity_id", "unit", "pricetype", "priceflag"]


def latest(stem: str) -> pathlib.Path:
    manifest = json.loads((RAW / "manifest.json").read_text(encoding="utf-8"))
    files = [m["file"] for m in manifest if m["stem"] == stem]
    return RAW / files[-1]


def md(df: pd.DataFrame) -> str:
    return df.to_markdown(index=False)


def main() -> None:
    path = latest("wfp_food_prices_nga")
    con = duckdb.connect()
    con.execute(f"CREATE TABLE p AS SELECT * FROM read_csv('{path.as_posix()}', header=true, all_varchar=true)")
    hxl = con.execute("SELECT COUNT(*) FROM p WHERE date LIKE '#%'").fetchone()[0]
    con.execute("DELETE FROM p WHERE date LIKE '#%'")          # HXL tag row, if HDX adds one
    con.execute("""CREATE TABLE t AS SELECT *, TRY_CAST(date AS DATE) AS d, TRY_CAST(price AS DOUBLE) AS px,
                   TRY_CAST(usdprice AS DOUBLE) AS usd FROM p""")
    q = lambda s: con.execute(s).df()
    s = []
    s.append(f"# Profile: {path.name}\n")
    s.append(f"_Generated by `pipeline/profile_wfp.py`. HXL tag rows removed: {hxl}._\n")

    s.append("## Size and span\n")
    s.append(md(q("""SELECT COUNT(*) AS rows, MIN(d) AS first_date, MAX(d) AS last_date, COUNT(DISTINCT d) AS dates,
                     COUNT(DISTINCT admin1) AS states, COUNT(DISTINCT market_id) AS markets,
                     COUNT(DISTINCT commodity_id) AS commodities,
                     COUNT(*) FILTER (WHERE d IS NULL) AS bad_dates, COUNT(*) FILTER (WHERE px IS NULL) AS bad_prices FROM t""")))
    s.append("\n\n## Missing values by column\n")
    cols = [r[0] for r in con.execute("DESCRIBE p").fetchall()]
    s.append(md(q("SELECT " + ", ".join(f"COUNT(*) - COUNT(NULLIF(TRIM({c}), '')) AS {c}" for c in cols) + " FROM p")))

    s.append("\n\n## Price types, flags and currency\n")
    s.append(md(q("SELECT pricetype, priceflag, currency, COUNT(*) AS rows FROM t GROUP BY ALL ORDER BY rows DESC")))

    s.append("\n\n## Rows per year and price type\n")
    s.append(md(q("""PIVOT (SELECT year(d) AS year, pricetype FROM t) ON pricetype USING COUNT(*) GROUP BY year ORDER BY year""")))

    s.append("\n\n## States: markets, rows and recent coverage\n")
    s.append(md(q("""SELECT admin1 AS state, COUNT(DISTINCT market_id) AS markets, COUNT(*) AS rows, MIN(d) AS first, MAX(d) AS last,
                     COUNT(*) FILTER (WHERE d > (SELECT MAX(d) FROM t) - INTERVAL 12 MONTH) AS rows_last_12m
                     FROM t GROUP BY 1 ORDER BY rows DESC""")))

    s.append("\n\n## Commodities: units, rows and recent coverage (top 40 by rows)\n")
    s.append(md(q("""SELECT category, commodity, STRING_AGG(DISTINCT unit, ', ') AS units, COUNT(*) AS rows,
                     COUNT(DISTINCT admin1) AS states, MIN(d) AS first, MAX(d) AS last,
                     COUNT(*) FILTER (WHERE d > (SELECT MAX(d) FROM t) - INTERVAL 12 MONTH) AS rows_last_12m
                     FROM t GROUP BY ALL ORDER BY rows DESC LIMIT 40""")))
    s.append(f"\n\nDistinct commodities in total: {con.execute('SELECT COUNT(DISTINCT commodity) FROM t').fetchone()[0]}\n")

    s.append("\n## Duplicates\n")
    k = ", ".join(KEY)
    s.append(md(q(f"""SELECT (SELECT COUNT(*) FROM t) - (SELECT COUNT(*) FROM (SELECT DISTINCT * FROM p)) AS exact_duplicate_rows,
                      (SELECT COUNT(*) FROM (SELECT {k} FROM t GROUP BY ALL HAVING COUNT(*) > 1)) AS keys_with_more_than_one_price""")))

    s.append("\n\n## Suspicious prices\n")
    s.append("Prices of zero or below, and prices more than 10x or less than 1/10 of the median for the same commodity, unit, price type and year.\n\n")
    s.append(md(q("""WITH m AS (SELECT commodity, unit, pricetype, year(d) AS y, MEDIAN(px) AS med FROM t GROUP BY ALL)
                     SELECT COUNT(*) FILTER (WHERE px <= 0) AS zero_or_negative,
                            COUNT(*) FILTER (WHERE px > 10 * med) AS over_10x_median,
                            COUNT(*) FILTER (WHERE px < med / 10) AS under_tenth_median
                     FROM t JOIN m ON t.commodity = m.commodity AND t.unit = m.unit AND t.pricetype = m.pricetype AND year(t.d) = m.y""")))

    s.append("\n\n## Implied exchange rate (price / usdprice), by year\n")
    s.append(md(q("""SELECT year(d) AS year, ROUND(MEDIAN(px / NULLIF(usd, 0)), 1) AS median_ngn_per_usd,
                     ROUND(MIN(px / NULLIF(usd, 0)), 1) AS min, ROUND(MAX(px / NULLIF(usd, 0)), 1) AS max
                     FROM t WHERE currency = 'NGN' GROUP BY 1 ORDER BY 1""")))

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(s) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
